def _monta():
    for c, corpo in _x.items():
        w = len(corpo[0])
        vazio = "." * w
        if c == "f":  # gancho no alto, senao vira t
            topo = [".##", "#..", "#.."]
        elif c in _asc:
            topo = [_asc[c]] * 3
        elif c == "i":
            topo = [vazio, "#", vazio]
        else:
            topo = [vazio] * 3
        G[c] = topo + corpo + [_desc.get(c, vazio)]
    for c, (base, ac) in _acc.items():
        corpo = [l.ljust(len(ac[0]), ".") for l in G[base][3:]]
        G[c] = ac + ["." * len(ac[0])] + corpo
    for c, g in G.items():
        G[c] = (g + ["." * len(g[0])] * 10)[:10]


_monta()


TIL = ["...", "...", "...", "...", "...", ".##", "##.", "...", "...", "..."]


def _pontos(g):
    return [(y, dx) for y, l in enumerate(g) for dx, ch in enumerate(l) if ch == "#"]


def tinta(texto, til=False):
    """conjunto de (linha, coluna) com tinta, linha 0-9, com "kerning": cada
    letra encosta o maximo possivel desde que fique pelo menos 1 texel vazio
    (que vira contorno) entre a tinta dela e a das anteriores; entre palavras,
    2 vazios. til=True poe o "~" do jogo nas duas pontas."""
    glifos = ([TIL] if til else []) + [None if c == " " else G[c] for c in texto] + ([TIL] if til else [])
    r, fim, ini_ant, espaco = set(), -2, 0, False
    for g in glifos:
        if g is None:
            espaco = True
            continue
        p = _pontos(g)
        x = fim + 3 if espaco else ini_ant + 1
        while any(abs(y - y2) < 2 and abs(x + dx - x2) < 2 for y, dx in p for y2, x2 in r):
            x += 1
        r |= {(y, x + dx) for y, dx in p}
        ini_ant, espaco = x, False
        fim = max(c for _, c in r)
    return r


def largura(texto, til=False):
    return max(c for _, c in tinta(texto, til)) + 1
